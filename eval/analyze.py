"""Build eval/results/summary.md and charts from metrics_{split}_{config}.json (all numbers trace here)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

R = Path(__file__).parent / "results"
EXPERIMENTS = {
    "E1 agent vs fixed pipeline": ["baseline_fixed", "agent_qwen"],
    "E2 model size (27B vs 30B-A3B)": ["agent_qwen", "agent_small"],
    "E3 claim check on/off": ["agent_qwen", "agent_qwen_noclaimcheck"],
    "E4 tight tool/round budget": ["agent_qwen", "agent_qwen_tight"],
    "E-Mistral different provider": ["agent_qwen", "agent_mistral"],
}


def load(split: str, cfg: str) -> dict[str, Any] | None:
    p = R / f"metrics_{split}_{cfg}.json"
    return json.loads(p.read_text())["summary"] if p.exists() else None


def ci(v: Any, pct: bool = False, d: int = 3) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, list):
        m, lo, hi = v
        return (
            f"{m * 100:.0f}% [{lo * 100:.0f}–{hi * 100:.0f}]"
            if pct
            else f"{m:.{d}f} [{lo:.{d}f}–{hi:.{d}f}]"
        )
    return f"{v * 100:.0f}%" if pct else f"{v:.{d}f}"


ROWS = [
    ("Routing accuracy (right company / clarify / not-found / refuse)", "route_acc", True),
    ("Risk level matches snapshot oracle", "risk_agree", True),
    ("Flag recall", "flag_recall", True),
    ("Flag precision", "flag_precision", True),
    ("Reports with ≥1 unsupported sentence (judge)", "reports_with_unsupported_sentence", True),
    ("Unsupported-sentence rate (judge)", "unsupported_sentence_rate", True),
    ("Unsupported-number rate (deterministic)", "unsupported_number_rate", True),
    ("Cost per report, GBP est.", "cost_gbp_mean", False),
    ("Latency mean, s", "latency_s_mean", False),
    ("Tool calls mean", "tool_calls_mean", False),
    ("Completed without hitting a guard", "complete_rate", True),
]


def table(split: str, cfgs: list[str]) -> str:
    ms = [load(split, c) for c in cfgs]
    head = "| Metric | " + " | ".join(cfgs) + " |\n|---|" + "---|" * len(cfgs) + "\n"
    body = ""
    for label, key, pct in ROWS:
        body += (
            f"| {label} | " + " | ".join(ci(m[key], pct) if m else "not run" for m in ms) + " |\n"
        )
    body += "| n items | " + " | ".join(str(m["n"]) if m else "-" for m in ms) + " |\n"
    return head + body


def charts(split: str) -> None:
    (R / "charts").mkdir(exist_ok=True)
    cfgs = [
        "baseline_fixed",
        "agent_qwen",
        "agent_small",
        "agent_qwen_noclaimcheck",
        "agent_qwen_tight",
    ]
    ms = {c: load(split, c) for c in cfgs}
    ms = {c: m for c, m in ms.items() if m}
    fig, ax = plt.subplots(1, 3, figsize=(14, 4))
    for a, (key, title) in zip(
        ax,
        [
            ("route_acc", "Routing accuracy"),
            ("risk_agree", "Risk agreement"),
            ("reports_with_unsupported_sentence", "Reports with unsupported sentence"),
        ],
        strict=True,
    ):
        names = list(ms)
        vals = [ms[c][key][0] for c in names]
        err = [
            [ms[c][key][0] - ms[c][key][1] for c in names],
            [ms[c][key][2] - ms[c][key][0] for c in names],
        ]
        a.bar(range(len(names)), vals, yerr=err, capsize=3, color="#1f5fbf")
        a.set_xticks(
            range(len(names)), [n.replace("agent_", "") for n in names], rotation=30, ha="right"
        )
        a.set_title(title)
        a.set_ylim(0, 1.05)
    fig.suptitle(f"{split} split, 95% bootstrap CI")
    fig.tight_layout()
    fig.savefig(R / "charts" / f"quality_{split}.png", dpi=130)
    plt.close(fig)
    fig, a = plt.subplots(figsize=(6, 4))
    for c, m in ms.items():
        a.scatter(
            m["cost_gbp_mean"][0],
            m["risk_agree"][0] if m["risk_agree"][0] == m["risk_agree"][0] else 0,
            s=60,
        )
        a.annotate(c.replace("agent_", ""), (m["cost_gbp_mean"][0], m["risk_agree"][0]))
    a.set_xlabel("mean cost / report (GBP est.)")
    a.set_ylabel("risk agreement")
    a.set_xscale("log")
    fig.tight_layout()
    fig.savefig(R / "charts" / f"cost_vs_quality_{split}.png", dpi=130)
    plt.close(fig)


def main() -> None:
    out = [
        "# CompanyLens evaluation summary\n",
        "Generated by `eval/analyze.py` from `eval/results/metrics_*.json`. Every number in the README traces here.\n",
        "Costs are estimates from token counts × a price table in `llm.py`, not provider invoices. "
        "Intervals are 95% bootstrap CIs over items (2000 resamples, fixed seed); with n≈15–54 they are wide.\n",
    ]
    for split in ("dev", "test"):
        if not any(load(split, c) for c in ["agent_qwen", "baseline_fixed"]):
            continue
        out.append(f"\n## {split.upper()} split\n")
        for name, cfgs in EXPERIMENTS.items():
            out.append(f"\n### {name}\n\n" + table(split, cfgs))
        cats = {
            c: (load(split, c) or {}).get("route_by_category")
            for c in ["baseline_fixed", "agent_qwen"]
        }
        out.append(
            "\n### Routing accuracy by category\n\n```\n" + json.dumps(cats, indent=1) + "\n```\n"
        )
        charts(split)
    e5 = R / "e5.json"
    if e5.exists():
        d = json.loads(e5.read_text())
        out.append(
            f"\n## E5 prompt injection\n\nResisted {d['resisted']}/{d['n']} poisoned runs ({d.get('invalid', 0)} invalid) "
            "(risk level, flag set, no prompt leak, no obeyed claim, tool budget).\n"
        )
    if load("fresh", "agent_qwen_v2"):
        out.append(
            "\n## Resolver change: ask whenever several live companies share a bare name\n\n"
            "v1 = resolver used for the original test run (test numbers above are v1 and were NOT re-run). "
            "v2 = new rule. Dev was used while designing v2; the fresh set (15 names never used before, "
            "`eval/companies/fresh.jsonl`, seed 1127) was built before v2 was evaluated and is run once per config. "
            "This is a dev + fresh-set improvement, not a test-split result.\n"
        )
        out.append(
            "\n### Fresh set (n=15: 5 clear, 5 ambiguous, 5 not-found)\n\n"
            + table("fresh", ["agent_qwen_v1", "agent_qwen_v2", "baseline_fixed_v2"])
        )
        out.append("\n### Dev (n=26)\n\n" + table("dev", ["agent_qwen", "agent_qwen_v2"]))
    for extra in ("memory.json", "spend.json"):
        p = R / extra
        if p.exists():
            out.append(
                f"\n## {extra}\n\n```\n{json.dumps(json.loads(p.read_text()), indent=1)[:1500]}\n```\n"
            )
    (R / "summary.md").write_text("".join(out))
    print("wrote summary.md")


if __name__ == "__main__":
    main()
